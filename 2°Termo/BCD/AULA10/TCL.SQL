 --EX2: COMMIT - CONFIRMANDO AS ALTERAÇÕES REALIZADAS

 START TRANSACTION;
 SELECT* FROM produto WHERE ID_PRODUTO=1;

 UPDATE produto
 SET preco=9.00
 WHERE ID_PRODUTO=1;
 SELECT*FROM PRODUTO WHERE ID_PRODUTO=1;

